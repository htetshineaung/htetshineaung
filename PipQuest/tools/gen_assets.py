def rows(art):
    r = [l for l in art.strip("\n").split("\n")]
    assert len(r) == 8 and all(len(x) == 8 for x in r), art
    return r

def to_bytes(art, mirror=False):
    r = rows(art)
    if mirror:
        r = [x[::-1] for x in r]
    out = []
    for c in range(8):
        b = 0
        for y in range(8):
            if r[y][c] == "#":
                b |= 1 << y
        out.append(b)
    return out

def sprite(name, frames):
    data = [8, 8]
    for f in frames:
        data += f
    body = ", ".join("0x%02X" % b for b in data)
    return "const uint8_t PROGMEM %s[] = {\n  %s\n};\n" % (name, body)

