def column(g, x, height, c="#"):  # stacks on top of ground (row 5 upward)
    for i in range(height):
        g[5 - i][x] = c

def hrow(g, x0, x1, y, c):
    for x in range(x0, x1 + 1):
        g[y][x] = c

def flag(g, x):
    for y in range(1, 6):
        g[y][x] = "F"

